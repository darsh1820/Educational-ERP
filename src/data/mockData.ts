export function calculateGrade(
  midterm: number,
  finalExam: number,
  practicum: number,
  continuous: number
): { weightedTotal: number; letterGrade: string } {
  // Weights: Midterm 30%, Final 40%, Practicum 20%, Continuous 10%
  const total = midterm * 0.3 + finalExam * 0.4 + practicum * 0.2 + continuous * 0.1;
  const weightedTotal = Math.round(total * 10) / 10;

  let letter = 'F';
  if (weightedTotal >= 93) letter = 'A';
  else if (weightedTotal >= 90) letter = 'A-';
  else if (weightedTotal >= 87) letter = 'B+';
  else if (weightedTotal >= 83) letter = 'B';
  else if (weightedTotal >= 80) letter = 'B-';
  else if (weightedTotal >= 77) letter = 'C+';
  else if (weightedTotal >= 73) letter = 'C';
  else if (weightedTotal >= 70) letter = 'C-';
  else if (weightedTotal >= 60) letter = 'D';

  return { weightedTotal, letterGrade: letter };
}

